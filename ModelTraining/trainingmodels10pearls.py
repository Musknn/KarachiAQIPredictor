    mse_scores = []
    rmse_scores = []
    r2_scores = []

    print(f"Training {name}...")

    for train_idx, val_idx in tscv.split(X_train_val):
        X_tr, y_tr = X_train_val.iloc[train_idx], y_train_val.iloc[train_idx]
